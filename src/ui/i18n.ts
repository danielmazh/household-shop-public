/**
 * True when this device already has app data or a Supabase session from
 * before spec 011: such a user is not asked for a language.
 */
function hasAppState(): boolean {
  for (let n = 0; n < localStorage.length; n++) {
    const key = localStorage.key(n) ?? '';
    if (key.startsWith(KEY_PREFIX) || key.startsWith('sb-')) return true;
  }
  return false;
}

/**
 * The saved language. None saved: Hebrew, saved silently for an old user,
 * and `chosen` false for a new one (spec 011, the language screen).
 */
function readLang(): { lang: Lang; chosen: boolean } {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'en' || saved === 'he') return { lang: saved, chosen: true };
    if (hasAppState()) {
      localStorage.setItem(LANG_KEY, 'he');
      return { lang: 'he', chosen: true };
    }
    return { lang: 'he', chosen: false };
  } catch {
    // No storage (tests, some private modes): ask each time in a browser.
    return { lang: 'he', chosen: typeof document === 'undefined' };
  }
}

