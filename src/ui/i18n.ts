/** A Hebrew message from the domain, in the active language. Unknown messages stay as they are. */
export function domainText(message: string, lang: Lang = current): string {
  if (lang === 'he') return message;
  for (const [re, write] of DOMAIN_EN) {
    const m = message.match(re);
    if (m) return write(m);
  }
  return message;
}
