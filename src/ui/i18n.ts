const DICTS: Record<Lang, Dict> = { he, en };

/** The text for a key in the active language. Some values are functions: `t('items')(3)`. */
export function t<K extends keyof Dict>(key: K): Dict[K] {
  return DICTS[current][key];
}

/** Sets `<html lang dir>` and the page title for the active language. */
export function applyLang() {
  if (typeof document === 'undefined') return;
  document.documentElement.lang = current;
  document.documentElement.dir = current === 'en' ? 'ltr' : 'rtl';
  document.title = t('appName');
  // Spec 011: the meta text and the install manifest follow too (public/lang.js does it before the first paint).
  document.querySelector('meta[name="description"]')?.setAttribute('content', t('appDescription'));
  document.querySelector('link[rel="manifest"]')?.setAttribute('href', current === 'en' ? './manifest.en.webmanifest' : './manifest.webmanifest');
}

/** Changes the language on this device and redraws the app. */
export function setLang(next: Lang) {
  current = next;
  chosen = true;
  try {
    localStorage.setItem(LANG_KEY, next);
  } catch {
    // Private mode: the choice lasts until the page closes.
  }
  applyLang();
  for (const listener of listeners) listener();
}

/** The active language; the component redraws when it changes. */
export function useLang(): Lang {
  // A counter, not the language: the first-run choice of Hebrew (spec 011) must redraw too.
  const [, setTick] = useState(0);
  useEffect(() => {
    const listener = () => setTick((n) => n + 1);
    listeners.add(listener);
    return () => {
      listeners.delete(listener);
    };
  }, []);
  return current;
}

